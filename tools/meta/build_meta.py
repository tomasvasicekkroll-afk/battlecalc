import json, sys
NAMES={"adepta-sororitas":"Adepta Sororitas","adeptus-custodes":"Adeptus Custodes","adeptus-mechanicus":"Adeptus Mechanicus","aeldari":"Aeldari","astra-militarum":"Astra Militarum","black-templars":"Black Templars","blood-angels":"Blood Angels","chaos-daemons":"Chaos Daemons","chaos-knights":"Chaos Knights","chaos-space-marines":"Chaos Space Marines","dark-angels":"Dark Angels","death-guard":"Death Guard","deathwatch":"Deathwatch","drukhari":"Drukhari","emperors-children":"Emperor's Children","genestealer-cult":"Genestealer Cult","grey-knights":"Grey Knights","imperial-agents":"Imperial Agents","imperial-knights":"Imperial Knights","leagues-of-votann":"Leagues of Votann","necrons":"Necrons","orks":"Orks","space-marines":"Space Marines","space-wolves":"Space Wolves","tau-empire":"T'au Empire","thousand-sons":"Thousand Sons","tyranids":"Tyranids","world-eaters":"World Eaters"}
merged={}
for f in sys.argv[1:]:
    merged.update(json.load(open(f,encoding='utf-8')))
out={}
for h,v in sorted(merged.items(), key=lambda kv: NAMES[kv[0].split('/')[-1]]):
    if not v.get('groups'): continue
    out[NAMES[h.split('/')[-1]]]=v
hdr='''// Tournament meta snapshot for all factions (generated by a script, not hand-written).
// Source: listhammer.info faction pages, 11th edition: the 4-1-or-better lists of 16+ player
// events from the LAST 30 DAYS (see `period`), read one by one (list text in the modal); only
// English lists with a readable datasheet list count. Win rate / games / detachment win rates are
// the site's "Last 4 Weeks" numbers. Groups are exact detachment combinations (n >= 3), plus
// "any:<detachment>" (n >= 2) for a detachment without a group of its own. A unit is only counted
// in lists that use the SAME detachment(s).
// unit rows: [datasheet, % of those lists with it, typical copies (median), max copies,
// average points per copy, section A/C/B/T/O/L].
export const META_LISTS_AUTO = '''
open('../../src/data/metaListsAuto.js','w',encoding='utf-8').write(hdr+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n')
print(len(out),'factions', len(json.dumps(out,ensure_ascii=False))//1024,'KB')
