"""Turn the browser export of matchup data into src/data/matchData.js.

Usage (from tools/meta):
  python build_matchups.py "<saved tool output file>"
The tool output file holds the string "JSONSTART" + JSON.stringify(__MU.exportAll()) + "JSONEND".
"""
import json, sys

raw = json.load(open(sys.argv[1], encoding="utf-8"))
txt = raw[0]["text"] if isinstance(raw, list) else raw
body = txt[txt.index("JSONSTART") + 9 : txt.rindex("JSONEND")]
try:
    data = json.loads(body)
except Exception:
    data = json.loads(json.loads('"' + body + '"'))

hdr = """// Matchup data for the team planner (generated by tools/meta/build_matchups.py, not hand-written).
// Source: listhammer.info faction pages, 11th edition.
//  windows["4w"]: the site's own "Matchups" table of each faction, Last 4 Weeks, all players
//     rows = [opponent faction, win rate % (null when < 10 games), avg point diff, games]
//  lists: round-by-round results of 4-1-or-better lists of the last `days` days before `capturedAt`
//     [faction idx, day (days since 2026-01-01), disposition idx (0 none, 1.. Purge the Foe, Take and Hold,
//      Priority Assets, Disruption, Reconnaissance), result %, [[opponent faction idx, 1 win / 0.5 draw / 0 loss]]]
export const MATCH_RAW = """
out = "../../src/data/matchData.js"
open(out, "w", encoding="utf-8").write(hdr + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
rounds = sum(len(l[4]) for l in data["lists"])
print(len(data["factions"]), "factions,", len(data["lists"]), "lists,", rounds, "rounds ->", out)
