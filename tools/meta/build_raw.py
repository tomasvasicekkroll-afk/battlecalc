"""Turn the browser export of raw tournament lists into src/data/metaRaw.js.

Usage (from tools/meta):
  python export_raw_to_json.py <saved tool output file>      # writes raw_export.json
  python build_raw.py raw_export.json [periodDays]           # writes ../../src/data/metaRaw.js
"""
import json, sys, datetime

src = sys.argv[1]
period = int(sys.argv[2]) if len(sys.argv) > 2 else 62
data = json.load(open(src, encoding="utf-8"))
factions = {}
for href, v in sorted(data.items(), key=lambda kv: kv[1]["name"]):
    if not v.get("lists"):
        continue
    factions[v["name"]] = {k: v[k] for k in ("source", "siteStats", "listsSeen", "names", "dets", "enhs", "lists")}
today = datetime.date.today().isoformat()
raw = {
    "capturedAt": today,
    "periodDays": period,
    "disps": ["", "Purge the Foe", "Take and Hold", "Priority Assets", "Disruption", "Reconnaissance"],
    "factions": factions,
}
hdr = """// Raw tournament lists (generated by a script, see tools/meta/README.md - not hand-written).
// Source: listhammer.info faction pages, 11th edition: 4-1-or-better lists of 16+ player events,
// the last `periodDays` days before `capturedAt`, only English lists with a readable datasheet list.
// Compact encoding (indexes into names / dets / enhs of the faction):
//   list = [day (days since 2026-01-01), result % (wins/games), disposition index (disps),
//           [detachment idx], [[datasheet idx, points, section idx in "ACBTOL"]], [enhancement idx]]
export const META_RAW = """
out = "../../src/data/metaRaw.js"
open(out, "w", encoding="utf-8").write(hdr + json.dumps(raw, ensure_ascii=False, separators=(",", ":")) + ";\n")
n = sum(len(f["lists"]) for f in factions.values())
print(len(factions), "factions,", n, "lists,", round(len(json.dumps(raw, ensure_ascii=False)) / 1024), "KB ->", out)
